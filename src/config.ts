import * as THREE from "three";

/**
 * 全部可调参数集中在这里。改"看起来对不对"通常只改这一个文件。
 *
 * 分三类：
 *   1. SCENE    —— 换素材、换机位（唯一需要动的配置）
 *   2. 追踪     —— 头部动作到画面的映射
 *   3. 时间常数 —— 平滑与回中
 */

// ————————————————————————————————————————————————
// 1. 场景
// ————————————————————————————————————————————————

/**
 * 把 public/ 下的文件解析成绝对 URL。
 *
 * 不能写死 "/splats/xxx"：GitHub Pages 的项目站点挂在 /<repo>/ 子路径下，
 * 以 / 开头会指到域名根，场景直接 404。这里用 Vite 的 BASE_URL 加上文档地址
 * 拼出完整 URL，本地开发、子路径部署、自定义域名三种情况都成立；
 * 传给 3DGS 库的也始终是绝对地址，库内部丢给 Worker 时不会二次解析出错。
 */
const assetUrl = (path: string) =>
  new URL(`${import.meta.env.BASE_URL}${path}`, document.baseURI).href;

/**
 * 3DGS 房间。
 *
 * 换素材时要注意三件事，它们都由数据决定、无法从代码推断：
 *   - 数据集的"上"方向（COLMAP 系常上下颠倒）
 *   - 房间内部的站立点（anchor）
 *   - 世界的尺度（scale，只影响视差强度，不影响构图）
 *
 * 这几个值是用离线点云渲染逐视角比对出来的，换素材请照同样办法重新标定。
 */
export const SCENE = {
  url: assetUrl("splats/playroom.spz"),
  label: "playroom · Deep Blending · 3DGS 30k",
  /**
   * 场景文件的实际字节数（SPZ 压缩后）。只用来算下载百分比。
   * 不能从响应的 Content-Length 推：Pages 会 gzip 传输，那是压缩后的大小，
   * 而流里读到的是解压后的字节，两个数对不上，百分比会冲到 200%。
   * 换素材时顺手改一下，写错只影响进度条，不影响加载。
   */
  bytes: 30_100_604,
  /**
   * 房间内部的站立点（数据集自己的世界坐标）。
   * 它会被钉在中性相机位置上，所以这就是"你把眼睛放进房间的哪个点"。
   * z 越负 = 站得越靠后，画面越"退远"、看到的房间越完整。
   */
  anchor: new THREE.Vector3(0.3, 0.23, -2.8),
  /** 绕 X 翻转（度）：修正数据集的上下方向。Deep Blending 需要 180°。 */
  pitch: 180,
  /** 绕 Y 旋转（度）：选朝向。 */
  yaw: 0,
  /**
   * 整体缩放。注意：**它不影响构图**——平移是按 anchor × scale 反推的，
   * 等比缩放后画面完全一致。它真正控制的是"同样幅度的头部动作对应多大视差"：
   * 调小 = 视差更强（房间显得更小），调大 = 更像真实房间尺度。
   */
  scale: 0.5,
  /** 视点进退（房间单位）的默认值，面板上可调。正 = 后退。 */
  dolly: 0,
};

// ————————————————————————————————————————————————
// 2. 追踪
// ————————————————————————————————————————————————

/**
 * 中性眼睛距离（世界单位）：人脸距摄像头约 60 cm 时，眼睛到虚拟屏幕的距离。
 * 相机、投影、场景锚点都以它为基准，保证两层坐标系一致。
 */
export const NEUTRAL_DIST = 1.6;

/**
 * 相机随头部平移的软上限（世界单位）。虚拟屏幕半宽为 1，所以 0.65 已经相当于
 * 横向移动超过大半屏——再大一定会穿进墙或家具里（穿墙 = 满屏巨大的模糊高斯）。
 */
export const HEAD_OFFSET_LIMIT = 0.65;

/** 转头跟随的角度上限（度）。这套数据只有正前方拍实，转太多两侧是糊的。 */
export const ROT_LIMIT_DEG = 30;

/** 俯仰上限按左右上限的比例折算：抬头低头能看到的内容比左右更少。 */
export const ROT_PITCH_RATIO = 0.6;

/**
 * 转角的符号。
 *
 * `pose-math.ts` 已经把手部/脸部矩阵归一化成固定的约定
 * （yaw > 0 = 转向你自己的左边，pitch > 0 = 抬头），所以在当前
 * MediaPipe 版本上这个符号是 1，实测通过。
 *
 * 如果换了一个大版本后方向反了，把这里改成 -1 —— 这是唯一该动的地方。
 */
export const ROT_SIGN = 1;

// ————————————————————————————————————————————————
// 3. 时间常数
// ————————————————————————————————————————————————

/**
 * 位姿输出的平滑时间常数（秒）。检测值可能一帧突变（重新捕获、边缘错乱、
 * 丢帧后恢复），直接喂给相机就是肉眼看到的闪烁；这里把突变抹成一段滑动。
 * 0.085 既跟得上快速转头，又能吃掉 30fps 检测的所有台阶。
 */
export const POSE_TAU = 0.085;

/**
 * 丢失追踪后回中的时间常数：刻意慢得多，让"归位"是一次几乎察觉不到的漂移，
 * 而不是一段明显的动画。
 */
export const POSE_RECENTER_TAU = 0.35;
